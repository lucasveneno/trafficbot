/** Structured error codes for update/rollback operations. */
export const UpdateErrorCode = {
  UPDATE_MANIFEST_UNAVAILABLE: 'UPDATE_MANIFEST_UNAVAILABLE',
  UPDATE_SIGNATURE_INVALID:    'UPDATE_SIGNATURE_INVALID',
  UPDATE_MANIFEST_INVALID:     'UPDATE_MANIFEST_INVALID',
  UPDATE_ARTIFACT_NOT_FOUND:   'UPDATE_ARTIFACT_NOT_FOUND',
  UPDATE_DOWNLOAD_FAILED:      'UPDATE_DOWNLOAD_FAILED',
  UPDATE_DOWNLOAD_TIMEOUT:     'UPDATE_DOWNLOAD_TIMEOUT',
  UPDATE_SIZE_MISMATCH:        'UPDATE_SIZE_MISMATCH',
  UPDATE_CHECKSUM_MISMATCH:    'UPDATE_CHECKSUM_MISMATCH',
  UPDATE_DRAIN_TIMEOUT:        'UPDATE_DRAIN_TIMEOUT',
  UPDATE_PERMISSION_DENIED:    'UPDATE_PERMISSION_DENIED',
  UPDATE_REPLACE_FAILED:       'UPDATE_REPLACE_FAILED',
  UPDATE_RESTART_FAILED:       'UPDATE_RESTART_FAILED',
  UPDATE_VERSION_MISMATCH:     'UPDATE_VERSION_MISMATCH',
  UPDATE_ALREADY_RUNNING:      'UPDATE_ALREADY_RUNNING',
  UPDATE_DOWNGRADE_BLOCKED:    'UPDATE_DOWNGRADE_BLOCKED',
  UPDATE_SERVER_UPGRADE_REQUIRED: 'UPDATE_SERVER_UPGRADE_REQUIRED',
  ROLLBACK_UNAVAILABLE:        'ROLLBACK_UNAVAILABLE',
  ROLLBACK_FAILED:             'ROLLBACK_FAILED',
  UPDATE_DEV_MODE:             'UPDATE_DEV_MODE',
} as const;

export type UpdateErrorCodeType = typeof UpdateErrorCode[keyof typeof UpdateErrorCode];

export class UpdateError extends Error {
  constructor(public readonly code: UpdateErrorCodeType, message: string) {
    super(message);
    this.name = 'UpdateError';
  }
}
